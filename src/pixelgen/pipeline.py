from __future__ import annotations

from pathlib import Path
from typing import Optional

from PIL import Image

_pipe = None  # singleton — loaded once on first call

# Default paths (relative to repo root)
DEFAULT_MODEL_DIR = Path("models/pixel-art-model")
DEFAULT_LORA_DIR = Path("models/loras")
DEFAULT_LORA_FILE = "PixelArtRedmond15V-PixelArt-PIXARFK.safetensors"

# --- Prompt templates --------------------------------------------------------
# ISSUE(v0): mixes "16-bit" and "8-bit" style tokens
# ISSUE(v0): "no anti-aliasing" in positive prompt can backfire with SD
# ISSUE(v0): missing LoRA trigger word "PixArFK"
PIXEL_ART_PREFIX = (
    "pixel art, 16-bit sprite, pixelated, sharp pixels, "
    "no anti-aliasing, retro game asset, flat colors, "
)

PIXEL_ART_NEGATIVE = (
    "blurry, painting, photorealistic, smooth, soft edges, "
    "watercolor, oil painting, 3d render, antialiased, "
    "high resolution, detailed textures, "
)


def load_pipeline(
    model_dir: Path = DEFAULT_MODEL_DIR,
    lora_dir: Path = DEFAULT_LORA_DIR,
    lora_file: str = DEFAULT_LORA_FILE,
    lora_scale: float = 0.9,
):
    """Load and return the SD + LCM + LoRA pipeline (cached as singleton)."""
    global _pipe
    if _pipe is not None:
        return _pipe

    from diffusers import StableDiffusionPipeline, LCMScheduler
    import torch

    if not model_dir.is_dir():
        raise FileNotFoundError(f"Model directory does not exist: {model_dir}")

    device = "cuda" if torch.cuda.is_available() else "cpu"
    dtype = torch.float16 if device == "cuda" else torch.float32

    _pipe = StableDiffusionPipeline.from_pretrained(
        str(model_dir),
        torch_dtype=dtype,
        local_files_only=True,
        feature_extractor=None,
        safety_checker=None,
    ).to(device)

    _pipe.scheduler = LCMScheduler.from_config(_pipe.scheduler.config)

    # Load and fuse LoRA
    lora_path = lora_dir / lora_file
    if lora_path.exists():
        _pipe.load_lora_weights(str(lora_dir), weight_name=lora_file)
        _pipe.fuse_lora(lora_scale=lora_scale)
    else:
        import warnings
        warnings.warn(f"LoRA file not found: {lora_path}. Running without LoRA.")

    return _pipe


def generate(
    prompt: str,
    width: int = 32,
    height: int = 32,
    seed: Optional[int] = None,
    num_steps: int = 8,
    guidance_scale: float = 1.8,
    gen_size: int = 512,
) -> Image.Image:
    """
    Generate a pixel-art sprite from a text prompt.

    Returns a PIL Image at (width × height) after pixelation and quantisation.

    Parameters
    ----------
    prompt : str
        User's text description (e.g. "small slime enemy").
    width, height : int
        Target sprite dimensions in pixels.
    seed : int or None
        RNG seed. None = random. v0 default was fixed at 42.
    num_steps : int
        LCM inference steps (v0 default: 8).
    guidance_scale : float
        CFG scale (v0 default: 1.8; 1.0 disables CFG).
    gen_size : int
        Internal generation resolution (v0 default: 512).
    """
    import torch
    from .postprocess import pixelate, quantise_colors

    # ISSUE(v0): prompt template hardcoded; missing LoRA trigger word
    full_prompt = (
        PIXEL_ART_PREFIX
        + f"8-bit pixel-art of {prompt}, retro game sprite, "
        + "solid background, NES style"
    )
    full_negative = PIXEL_ART_NEGATIVE + "smooth gradients, shadow shading"

    # ISSUE(v0): seed fixed at 42
    if seed is None:
        seed = 42
    generator = torch.manual_seed(seed)

    pipe = load_pipeline()

    # ISSUE(v0): blocking call — should use run_in_executor in async context
    result = pipe(
        full_prompt,
        negative_prompt=full_negative,
        width=gen_size,
        height=gen_size,
        num_inference_steps=num_steps,
        guidance_scale=guidance_scale,
        generator=generator,
    )
    image = result.images[0]

    # Post-process: pixelate → resize → quantise
    image = image.convert("RGBA")
    image = pixelate(image, pixel_size=8)

    # ISSUE(v0): naive nearest-neighbour resize loses grid cells for small targets
    if width <= 32:
        image = image.resize((256, 256), Image.NEAREST)
    image = image.resize((width, height), Image.NEAREST)

    image = quantise_colors(image, num_colors=32)

    return image
